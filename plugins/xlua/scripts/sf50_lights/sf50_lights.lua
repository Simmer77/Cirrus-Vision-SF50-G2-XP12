--===| FLIGHT START |====================================================================
function flight_start()

    -- INITIALIZE ALL MODES -------------------------------------------------------------
    init_lights_all_modes()

    -- INITIALIZE TO COLD & DARK --------------------------------------------------------
    if simDR_startup_running == 0 then
        init_lights_CD()

    -- INITIALIZE TO ENGINES RUNNING ----------------------------------------------------
    elseif simDR_startup_running == 1 then
		init_lights_ER()

    end

end



