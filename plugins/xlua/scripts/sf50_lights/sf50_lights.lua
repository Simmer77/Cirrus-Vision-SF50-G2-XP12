--===| AI INITIALIZE (Auto-Board / Auto-Start) |=========================================
function init_lights_AI()

    if sf50DR_init_lights_AI == 1 then	-- Monitor AI for auto-board call
        init_lights_all_modes()
        init_lights_CD()

		simDR_strobe_lights_on = 0
		simDR_landing_lights_on = 0
		simDR_navigation_lights_on = 0

        sf50DR_init_lights_AI = 2
    end

end



